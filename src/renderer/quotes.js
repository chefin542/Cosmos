// 모든 명언을 한 번씩 섞어 보여 준 뒤 다시 섞는다(셔플 백).
// 새로 섞을 때도 방금 본 명언이 연달아 나오지 않게 한다.
export function createQuoteRotator(quotes = QUOTES, random = Math.random) {
  let bag = [];
  let last = null;

  function refill() {
    bag = quotes.slice();
    for (let i = bag.length - 1; i > 0; i--) {
      const j = Math.floor(random() * (i + 1));
      [bag[i], bag[j]] = [bag[j], bag[i]];
    }
    if (bag.length > 1 && bag[bag.length - 1] === last) {
      [bag[0], bag[bag.length - 1]] = [bag[bag.length - 1], bag[0]];
    }
  }

  return {
    next() {
      if (bag.length === 0) refill();
      last = bag.pop();
      return last;
    },
  };
}
